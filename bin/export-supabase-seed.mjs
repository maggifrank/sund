#!/usr/bin/env node
/* Write supabase/seed.sql: the shared pool list and what sundlaugar.is says
 * about each pool, from the same lib/pools.js and lib/poolinfo.js the app has
 * always shipped. Git stays the source of truth; the database is loaded from
 * it, so the nightly crawl's PRs keep working as they do now.
 *
 * Every statement is an upsert, so running the file again after a crawl
 * updates names, positions and details without touching anyone's swims. A
 * pool that has been renamed keeps its id, and the swims pointing at it.
 *
 * Usage: node bin/export-supabase-seed.mjs [out]   (default supabase/seed.sql)
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BUILT_IN, ABROAD } from '../lib/pools.js';
import { POOL_INFO } from '../lib/poolinfo.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = process.argv[2] || path.join(ROOT, 'supabase', 'seed.sql');

const lit = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (Number.isFinite(v) ? String(v) : 'null');

const regionOf = new Map(POOL_INFO.map((p) => [p.id, p.region ?? null]));

const pools = [
  ...BUILT_IN.map((p) => ({ ...p, country: 'IS' })),
  ...ABROAD.map((p) => ({ ...p, country: p.country ?? null }))
];

const poolRows = pools.map((p) =>
  `  (${lit(p.id)}, ${lit(p.name)}, ${lit(p.country)}, ${lit(regionOf.get(p.id) ?? null)}, ${num(p.lat)}, ${num(p.lon)})`);

const known = new Set(pools.map((p) => p.id));
const infoRows = POOL_INFO.filter((p) => known.has(p.id)).map((p) => {
  const { id, fetched, ...info } = p;
  return `  (${lit(id)}, ${lit(JSON.stringify(info))}::jsonb, ${lit(fetched)})`;
});
const skipped = POOL_INFO.filter((p) => !known.has(p.id)).map((p) => p.id);

const sql = `-- Generated by bin/export-supabase-seed.mjs from lib/pools.js and lib/poolinfo.js.
-- Do not edit by hand: change those files and run the script again.

insert into public.pools (id, name, country, region, lat, lon) values
${poolRows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, country = excluded.country, region = excluded.region,
  lat = excluded.lat, lon = excluded.lon;

insert into public.pool_info (pool_id, info, fetched) values
${infoRows.join(',\n')}
on conflict (pool_id) do update set info = excluded.info, fetched = excluded.fetched;
`;

await fs.mkdir(path.dirname(OUT), { recursive: true });
await fs.writeFile(OUT, sql);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${pools.length} pools, ${infoRows.length} with details` +
  (skipped.length ? ` (no pool for ${skipped.join(', ')})` : ''));
